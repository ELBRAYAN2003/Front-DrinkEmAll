export function Price({ price, discount = 0 }) {
  if (!discount) return <div className="price">{money(price)}</div>
  const old = money(price)
  const now = money(price * (1 - discount / 100))
  return (
    <div className="price">
      <span className="old">{old}</span>
      <span className="price-off">-{discount}% Off</span>
      <span className="now">{now}</span>
    </div>
  )
}